export const DICTIONARIES = { en, ar, ku };

export function getLanguage(code) {
  return LANGUAGES.find((l) => l.code === code) || LANGUAGES[0];
}

export function translate(lang, key, vars) {
  const str = DICTIONARIES[lang]?.[key] ?? en[key] ?? key;
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

/** Western digits everywhere so prices match phone numbers and receipts. */
export function formatIQD(amount, lang) {
  return `${new Intl.NumberFormat('en-US').format(amount)} ${translate(lang, 'iqd')}`;
}

/** Product names are stored as name_ku / name_ar / name_en. */
export function localizedName(item, lang) {
  return item?.name?.[lang] || item?.name?.en || item?.name?.ku || '';
}
